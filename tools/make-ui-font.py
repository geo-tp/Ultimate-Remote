#!/usr/bin/env python3
"""Bake DejaVu Sans into compact antialiased framebuffer glyphs (Pillow required)."""
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
parts = ["// Generated by tools/make-ui-font.py. See UiFont.LICENSE.\n"
         "#pragma once\n#include <cstdint>\nnamespace platform::linux::ui_font {\n"
         "struct Glyph { uint32_t offset; uint8_t width; uint8_t advance; };\n"
         "struct Font { int height; const Glyph* glyphs; const uint8_t* pixels; };\n"]
for name, size, weight in [("Small", 10, ""), ("Body", 12, ""), ("Title", 16, "-Bold")]:
    font = ImageFont.truetype(f"/usr/share/fonts/truetype/dejavu/DejaVuSans{weight}.ttf", size)
    top = font.getbbox("Ag")[1]
    height = size + 2
    pixels = []
    glyphs = []
    for code in range(32, 127):
        char = chr(code)
        advance = math.ceil(font.getlength(char))
        width = max(advance, font.getbbox(char)[2])
        canvas = Image.new("L", (width, height))
        ImageDraw.Draw(canvas).text((0, -top), char, font=font, fill=255)
        glyphs.append((len(pixels), width, advance))
        pixels.extend(canvas.tobytes())
    parts.append(f"inline constexpr uint8_t {name}Pixels[] = {{\n")
    for offset in range(0, len(pixels), 32):
        parts.append(",".join(str(value) for value in pixels[offset:offset + 32]) + ",\n")
    parts.append(f"}};\ninline constexpr Glyph {name}Glyphs[] = {{\n")
    parts.extend("{%d,%d,%d},\n" % glyph for glyph in glyphs)
    parts.append(f"}};\ninline constexpr Font {name} = {{{height}, {name}Glyphs, {name}Pixels}};\n")
parts.append("}\n")
(root / "src/Platform/Linux/Assets/UiFont.h").write_text("".join(parts))
