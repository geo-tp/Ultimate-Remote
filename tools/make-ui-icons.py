#!/usr/bin/env python3
"""Bake shared icon paths into exact-size coverage masks (requires Pillow)."""
from pathlib import Path
from icon_art import ICON_NAMES, ICON_SIZES, icon_mask

parts = ["// Generated by tools/make-ui-icons.py from icon_art.py.\n"
         "#pragma once\n#include <cstdint>\nnamespace platform::linux::ui_icons {\n"
         "struct Mask { int size; const uint8_t* pixels; };\n"]
for name in ICON_NAMES:
    for size in ICON_SIZES:
        pixels = icon_mask(name, size).tobytes()
        parts.append(f"inline constexpr uint8_t {name}{size}[] = {{\n")
        for offset in range(0, len(pixels), 32):
            parts.append(",".join(str(value) for value in pixels[offset:offset + 32]) + ",\n")
        parts.append("};\n")
parts.append(f"inline constexpr Mask Icons[{len(ICON_NAMES)}][{len(ICON_SIZES)}] = {{\n")
for name in ICON_NAMES:
    parts.append("{" + ",".join(f"{{{size}, {name}{size}}}" for size in ICON_SIZES) + "},\n")
parts.append("};\n}\n")
target = Path(__file__).resolve().parents[1] / "src/Platform/Linux/Assets/UiIcons.h"
target.write_text("".join(parts))
